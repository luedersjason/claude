// Turn seed/seed.json ({collection: {docId: data}}) into seed/seed.sql for D1.
// Usage: node seed/load.mjs [collection,collection,...]
//   With no argument every collection in seed.json is written.
//   Re-seeding "reviews" or "issues" overwrites decisions and edits made on the site,
//   so on a live site pass only the collections you mean to replace, e.g. `node seed/load.mjs reviewItems`.
// Then: npx wrangler d1 execute nitto-watermain --local --file=seed/seed.sql   (drop --local for the real database)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const seed = JSON.parse(readFileSync(join(here, "seed.json"), "utf8"));
const only = process.argv[2] ? new Set(process.argv[2].split(",").map((s) => s.trim()).filter(Boolean)) : null;
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const now = Date.now();
const lines = ["-- Generated by seed/load.mjs from seed/seed.json on " + new Date(now).toISOString()];
let n = 0;
for (const [col, docs] of Object.entries(seed)) {
  if (only && !only.has(col)) continue;
  for (const [id, data] of Object.entries(docs || {})) {
    lines.push(`INSERT OR REPLACE INTO docs(col,id,data,ver,updated_at,updated_by) VALUES(${q(col)},${q(id)},${q(JSON.stringify(data))},1,${now},'seed');`);
    n++;
  }
}
writeFileSync(join(here, "seed.sql"), lines.join("\n") + "\n");
console.log(`seed.sql: ${n} documents` + (only ? ` (${[...only].join(", ")})` : ""));
